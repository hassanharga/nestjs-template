import 'reflect-metadata';
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { Server } from 'node:net';
import { NestFactory } from '@nestjs/core';
import { Test } from '@nestjs/testing';
import * as swagger from '../main.swagger';
import { OpenApiExportModule } from './export.module';
import { exportApiDocument, writeApiContract } from './export';

interface ExportedSchema {
  paths: Record<
    string,
    {
      get: { responses: Record<string, unknown> };
      post: {
        responses: Record<
          string,
          {
            content: Record<
              string,
              { schema: { properties: Record<string, unknown> } }
            >;
          }
        >;
      };
    }
  >;
  components: {
    schemas: Record<string, { properties: Record<string, unknown> }>;
  };
}

const originalEnv = { ...process.env };

afterEach(() => {
  process.env = { ...originalEnv };
  jest.restoreAllMocks();
});

it('exports versioned business routes, DTO constraints, and response envelopes without listening', async () => {
  const listen = jest.spyOn(Server.prototype, 'listen');
  const document = JSON.parse(await exportApiDocument()) as ExportedSchema;
  expect(Object.keys(document.paths).sort()).toEqual([
    '/v1',
    '/v1/items',
    '/v1/items/{id}',
  ]);
  const post = document.paths['/v1/items'].post;
  expect(
    post.responses['201'].content['application/json'].schema.properties,
  ).toMatchObject({
    success: { enum: [true] },
    data: { $ref: '#/components/schemas/ItemDto' },
  });
  expect(
    post.responses['400'].content['application/json'].schema.properties,
  ).toMatchObject({ success: { enum: [false] }, data: { enum: [null] } });
  expect(document.paths['/v1/items/{id}'].get.responses['404']).toBeDefined();
  expect(document.components.schemas.SetItemDto.properties).toMatchObject({
    id: { type: 'integer', exclusiveMinimum: true, minimum: 0 },
    name: { minLength: 1, maxLength: 100 },
  });
  expect(listen).not.toHaveBeenCalled();
});

it('keeps contract bytes independent of environment identities and optional capabilities', async () => {
  const baseline = await exportApiDocument();
  Object.assign(process.env, {
    APP_NAME: 'private-local-name',
    APP_DESCRIPTION: 'private description',
    APP_VERSION: '99.0.0',
    APP_REPOSITORY_URL: 'https://private.example/repository',
    NODE_ENV: 'development',
    FEATURE_MONITORING: 'true',
    FEATURE_RESILIENCE: 'true',
  });
  expect(await exportApiDocument()).toBe(baseline);
  expect(baseline).not.toContain('private');
});

it('checks generated bytes without modifying a stale or missing contract', async () => {
  const directory = await mkdtemp(join(tmpdir(), 'openapi-export-'));
  const path = join(directory, 'contract.json');
  try {
    await expect(writeApiContract(path, true)).rejects.toThrow('missing');
    await writeApiContract(path);
    await expect(writeApiContract(path, true)).resolves.toBeUndefined();
    await writeFile(path, 'stale\n');
    await expect(writeApiContract(path, true)).rejects.toThrow('out of date');
    expect(await readFile(path, 'utf8')).toBe('stale\n');
  } finally {
    await rm(directory, { recursive: true });
  }
});

it('closes the application when document generation fails', async () => {
  let closeCalls = 0;
  const fixture = await Test.createTestingModule({
    imports: [OpenApiExportModule],
    providers: [
      {
        provide: 'cleanup-probe',
        useValue: {
          onModuleDestroy: () => {
            closeCalls += 1;
          },
        },
      },
    ],
  }).compile();
  const app = fixture.createNestApplication();
  jest.spyOn(NestFactory, 'create').mockResolvedValueOnce(app);
  jest.spyOn(swagger, 'createApiDocument').mockImplementationOnce(() => {
    throw new Error('document generation failed');
  });
  try {
    await expect(exportApiDocument()).rejects.toThrow(
      'document generation failed',
    );
    expect(closeCalls).toBe(1);
  } finally {
    if (closeCalls === 0) await app.close();
  }
});
